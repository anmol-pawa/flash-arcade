// Generates out/sw.js for the static (installable) build. The service worker
// precaches every built file — pages, scripts, fonts and the ~17 MB PGlite
// runtime — so once the game has loaded online it keeps working offline,
// including when launched from the iPhone home screen.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const out = join(process.cwd(), "out");
const base = process.env.BASE_PATH ?? "";

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const hash = createHash("sha256");
const urls = [];
for (const file of walk(out).sort()) {
  const rel = relative(out, file).split(sep).join("/");
  if (rel === "sw.js" || rel === ".nojekyll" || rel.endsWith(".map")) continue;
  hash.update(rel).update(readFileSync(file));
  // serve directory indexes by their pretty URL too (…/campaign/)
  urls.push(`${base}/${rel}`);
  if (rel.endsWith("index.html")) urls.push(`${base}/${rel.slice(0, -"index.html".length)}`);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// generated by scripts/gen-sw.mjs — do not edit
const CACHE = "query-clash-${version}";
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("query-clash-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }).catch(() => (req.mode === "navigate" ? caches.match("${base}/") : Response.error())),
    ),
  );
});
`;
writeFileSync(join(out, "sw.js"), sw);
writeFileSync(join(out, ".nojekyll"), ""); // GitHub Pages: serve the _next/ folder
console.log(`sw.js: ${urls.length} files precached (cache ${version})`);
